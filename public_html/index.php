<script>
document.addEventListener('DOMContentLoaded', function(){
  var counters = document.querySelectorAll('.stat-counter');
  var counted = false;
  new IntersectionObserver(function(entries) {
    if (entries[0].isIntersecting && !counted) {
      counted = true;
      counters.forEach(function(el) {
        var delay = parseInt(el.dataset.delay) || 0;
        var target = parseInt(el.dataset.target) || 0;
        var suffix = el.dataset.suffix || '';
        setTimeout(function() {
          var step = 0, steps = 60;
          function tick() {
            step++;
            var val = Math.min(step * target / steps, target);
            el.textContent = (val >= 1000 ? (Math.round(val / 100) * 100).toLocaleString() : Math.round(val)) + suffix;
            if (step < steps) requestAnimationFrame(tick);
            else {
              el.textContent = (target >= 1000 ? target.toLocaleString() : target) + suffix;
              el.classList.add('popped');
              el.addEventListener('animationend', function() { el.classList.remove('popped'); }, { once: true });
            }
          }
          requestAnimationFrame(tick);
        }, delay);
      });
    }
  }, { threshold: 0.4 }).observe(document.getElementById('stats'));
});
</script>

